// Offline R2 behavior tests; no provider process or network access.
const assert = require("node:assert/strict");
const path = require("node:path");
module.exports = async function testR2(load, web) {
  const src = name => load(path.join(web, "src", name + ".ts"));
  const { TaskSchema, PlanSchema } = src("schema/plans.schema");
  const { DebateSchema } = src("schema/debates.schema");
  const { MutisSchema } = src("schema/mutis.schema");
  const { planRunOrder, planSummary, taskCanWrite } = src("components/features/plan/plan-order");
  const { debateReducer } = src("components/features/debate/debate-reducer");
  const { memoryNotice } = src("components/features/memory/memory-events");
  const { createPlanRunner, runnerServices } = src("components/features/plan/plan-runner");
  const { extractReview, nextReviewAction, buildFixTask } = src("components/features/plan/plan-gates");
  const { useCardStore } = src("components/features/chat/card-store");
  const { http } = src("lib/http");
  const { postSse } = src("lib/sse");
  const task = (id, extra = {}) => TaskSchema.parse({ id, title: `Việc ${id}`, detail: "Giữ tiếng Việt", assignee: "mock", kind: "code", ...extra });
  const plan = tasks => PlanSchema.parse({ id: crypto.randomUUID(), title: "Kế hoạch", folder: "C:/fixture", request: "Mock", approved: true, tasks });
  const cfg = extra => MutisSchema.parse({ enabled: false, roles: { lead: { provider_id: "mock", model: "m" }, big: {}, small: {} }, ...extra });
  assert.deepEqual(planRunOrder([task(3, { depends_on: [2] }), task(2, { depends_on: [1] }), task(1, { status: "xong" })]), [2, 3]);
  assert.throws(() => planRunOrder([task(1), task(1)]), /trùng/);
  assert.throws(() => planRunOrder([task(1, { depends_on: [4] })]), /Thiếu/);
  assert.throws(() => planRunOrder([task(1, { depends_on: [2] }), task(2, { depends_on: [1] })]), /vòng/);
  assert.throws(() => planRunOrder([task(1, { status: "xong", depends_on: [1] })]), /vòng/);
  assert.equal(taskCanWrite(task(1, { kind: "small_edit" })), true);
  assert.equal(taskCanWrite(task(1, { permission: "read" })), false);
  const summary = planSummary({ ...plan([task(1)]), title: "😀".repeat(2000) });
  assert.equal(Array.from(summary).length, 1500);
  assert.equal(summary.includes("\uFFFD"), false);
  assert.match(planSummary(plan([task(1)])), /Việc 1 · mock/);
  let live = { record: DebateSchema.parse({ id: "debate" }), activity: "", phase: "round", round: 1, live: true };
  for (const [event, data] of [["round", { round: 1 }], ["delta", { side: "codex", round: 1, text: "Xin chào" }], ["log", { side: "codex", round: 1, text: "Token: vào 123 ra 45" }], ["turn", { side: "claude", round: 1, turn: { text: "Đồng ý", agree: true, elapsed_s: 4 } }], ["judging", { model: "judge" }], ["verdict", { decision: "Kết hợp", plan_steps: ["Kiểm tra"] }]]) live = debateReducer(live, event, data);
  assert.equal(live.record.rounds[0].codex.text, "Xin chào");
  assert.equal(live.record.rounds[0].codex.tokens, 168);
  assert.equal(live.record.rounds[0].claude.agree, true);
  assert.equal(live.phase, "judge");
  live = debateReducer(live, "done", { ...live.record, status: "done", elapsed_s: 9 });
  assert.equal(live.live, false); assert.equal(live.record.elapsed_s, 9);
  assert.equal(DebateSchema.parse({ id: "old" }).elapsed_s, 0);
  assert.equal(TaskSchema.parse({ id: 1, title: "a", detail: "b", assignee: "p", kind: "code" }).fix_rounds_used, 0);
  assert.equal(extractReview('```json\n{"verdict":"PASS","notes":"brace } quoted"}\n```').verdict, "PASS");
  assert.equal(extractReview("broken").verdict, "FAIL");
  const blocking = extractReview('{"verdict":"FAIL","issues":[{"severity":"high","problem":"Sai"}]}');
  assert.equal(nextReviewAction(blocking, 0, 1), "create_fix");
  assert.equal(nextReviewAction(blocking, 1, 1), "fail");
  const fixture = plan([task(1, { fix_rounds_used: 1 })]);
  const fix = buildFixTask(fixture, fixture.tasks[0], "Sửa", "Lỗi");
  assert.match(fix.detail, /Giữ tiếng Việt/); assert.equal(fix.chat_id, null); assert.equal(fix.fix_rounds_used, 1);
  const requests = [], saved = [], transitions = [];
  const sse = events => new Response(events.map(([name, data]) => `event: ${name}\ndata: ${JSON.stringify(data)}\n\n`).join(""), { headers: { "content-type": "text/event-stream" } });
  const originalFetch = global.fetch;
  // R1 tests replaced the shared request method. Restore its real path/error handling via a fresh module instance is unnecessary:
  // this adapter still routes every R2 request through the mocked fetch below.
  http.request = (url, init) => fetch(`/api${url}`, init);
  let failWorker = false, verifyOK = true, reviewFail = false, missingDone = false;
  global.fetch = async (url, init = {}) => {
    const body = init.body ? JSON.parse(init.body) : {};
    requests.push({ url, body });
    if (url.includes("/stop")) return Response.json({ stopped: true });
    if (url.includes("/restore")) return Response.json({ ok: true });
    if (url.endsWith("/roles/resolve")) return Response.json({ lead: { used_provider: { id: "mock", name: "Mock", kind: "codex_cli", models: ["m"] } }, big: {}, small: {} });
    if (url.endsWith("/mutis/events")) return Response.json({ ok: true });
    if (url.endsWith("/plan-diff")) return Response.json({ diff: "+ sửa" });
    if (url.endsWith("/verify")) return sse([["log", { text: "Kiểm tra" }], ["verify", { ok: verifyOK, summary_lines: [verifyOK ? "Đạt" : "Sai"] }]]);
    if (init.method === "PUT") { saved.push(structuredClone(body)); return Response.json(body); }
    if (url.endsWith("/chat")) {
      const review = body.permission === "read" && body.messages[0].content.includes("Review task");
      const answer = review ? JSON.stringify(reviewFail ? blocking : { verdict: "PASS", issues: [] }) : "Hoàn tất<memory>{}</memory>";
      return sse([["delta", { text: answer }], ["log", { text: "Token: vào 12 ra 5" }], ...(failWorker ? [["error", { text: "Mock failure" }]] : []), ...(missingDone ? [] : [["done", {}]])]);
    }
    throw new Error(`Unexpected mock request ${url}`);
  };
  try {
    const notice = memoryNotice({ scope: "r2", status: "done", action: "archived" }, "C:/fixture");
    assert.match(notice.text, /Đã đóng scope r2/); await notice.action();
    assert.match(requests.at(-1).url, /r2\/restore\?folder=C%3A%2Ffixture/);
    assert.equal(memoryNotice({ scope: "r2", status: "active", action: "updated" }, "x").action, undefined);
    const providers = [{ id: "mock", name: "Mock", kind: "codex_cli", models: ["m"], agent_capable: false }];
    const progress = p => transitions.push(p.tasks.map(t => t.status).join(","));
    const first = plan([task(2, { depends_on: [1], permission: "full" }), task(1)]);
    await createPlanRunner(cfg({}), providers, runnerServices, progress).runWholePlan(first);
    assert.deepEqual(first.tasks.map(t => t.status), ["xong", "xong"]);
    const chats = requests.filter(r => r.url.endsWith("/chat"));
    assert.deepEqual(chats.slice(-2).map(r => r.body.task_id), ["1", "2"]);
    assert.equal(chats.at(-1).body.permission, "full"); assert.equal(chats.at(-1).body.plan_id, first.id);
    assert.notEqual(chats[0].body.chat_id, chats[1].body.chat_id);
    assert.equal(first.tasks[0].summary, "Hoàn tất");
    assert.ok(transitions.some(s => s.includes("đang chạy"))); assert.ok(saved.length >= 4);
    const reviewOnly = { ...plan([task(1, { status: "xong" }), task(2)]), auto_continue: true };
    const beforeReview = requests.filter(r => r.url.endsWith("/chat")).length;
    await createPlanRunner(cfg({}), providers).review(reviewOnly.tasks[0], reviewOnly);
    assert.equal(requests.filter(r => r.url.endsWith("/chat")).length, beforeReview);
    const before = requests.filter(r => r.url.endsWith("/chat")).length; await createPlanRunner(cfg({}), providers).runWholePlan(first);
    assert.equal(requests.filter(r => r.url.endsWith("/chat")).length, before);
    failWorker = true;
    const failed = plan([task(1), task(2, { depends_on: [1] })]);
    await createPlanRunner(cfg({}), providers).runWholePlan(failed);
    assert.equal(failed.tasks[0].status, "lỗi"); assert.equal(failed.tasks[1].status, "chờ");
    failWorker = false; missingDone = true;
    const partial = plan([task(1)]); await createPlanRunner(cfg({}), providers).runWholePlan(partial);
    assert.equal(partial.tasks[0].status, "lỗi"); missingDone = false;
    const gated = plan([task(1)]);
    await createPlanRunner(cfg({ enabled: true, verify_gate: true, auto_review: true }), providers).runWholePlan(gated);
    assert.equal(gated.tasks[0].verify.ok, true); assert.equal(gated.tasks[0].review.verdict, "PASS");
    verifyOK = false;
    const bounded = plan([task(1)]);
    await createPlanRunner(cfg({ enabled: true, verify_gate: true, auto_fix: true, fix_rounds_max: 2 }), providers).runWholePlan(bounded);
    assert.equal(bounded.tasks.length, 3); assert.equal(bounded.tasks[0].status, "lỗi");
    assert.equal(bounded.tasks[2].fix_rounds_used, 2); verifyOK = true; reviewFail = true;
    const reviewed = plan([task(1)]);
    await createPlanRunner(cfg({ enabled: true, auto_review: true, auto_fix: true, fix_rounds_max: 1 }), providers).runWholePlan(reviewed);
    assert.equal(reviewed.tasks.length, 2); assert.equal(reviewed.tasks[0].status, "lỗi");
    assert.equal(useCardStore.getState().running, null);
    const unapproved = { ...plan([task(1)]), approved: false };
    await assert.rejects(createPlanRunner(cfg({}), providers).runWholePlan(unapproved), /chưa được duyệt/);
    let started;
    const ready = new Promise(resolve => { started = resolve; });
    const services = { ...runnerServices, chat: async (_, signal) => { started(); await new Promise((resolve, reject) => signal.addEventListener("abort", () => reject(new DOMException("Stopped", "AbortError")), { once: true })); } };
    const cancelled = plan([task(1), task(2)]); const runner = createPlanRunner(cfg({}), providers, services);
    const active = runner.runWholePlan(cancelled); await ready; await runner.stop(); await active;
    assert.equal(cancelled.tasks[0].status, "đã dừng"); assert.equal(cancelled.tasks[1].status, "chờ");
    assert.ok(requests.some(r => /\/stop$/.test(r.url)));
    let gateStarted;
    const gateReady = new Promise(resolve => { gateStarted = resolve; });
    const gateServices = { ...runnerServices, verify: async (_, signal) => { gateStarted(); await new Promise((resolve, reject) => signal.addEventListener("abort", () => reject(new DOMException("Stopped", "AbortError")), { once: true })); } };
    const cancelledGate = plan([task(1)]);
    const gateRunner = createPlanRunner(cfg({ enabled: true, verify_gate: true }), providers, gateServices);
    const gateActive = gateRunner.runWholePlan(cancelledGate); await gateReady; await gateRunner.stop(); await gateActive;
    assert.equal(cancelledGate.tasks[0].status, "đã dừng");
    http.request = async () => sse([["plan", { id: "p" }]]);
    await postSse("/plans", {}, new AbortController().signal, () => {}, "plan");
    http.request = async () => sse([["log", { text: "partial" }]]);
    await assert.rejects(postSse("/plans", {}, new AbortController().signal, () => {}, "plan"));
    console.log("PASS R2: order/cycles, Unicode summary, debate reducer, memory undo, runner mock fetch, gates/review/fix bounds, cancellation, missing terminal event");
  } finally { global.fetch = originalFetch; }
};
